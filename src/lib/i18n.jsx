function normalizeLanguage(value) {
  const normalized = String(value || "").slice(0, 2).toLowerCase();
  return SUPPORTED_LANGUAGES.has(normalized) ? normalized : "fr";
}

function detectBrowserLanguage() {
  if (typeof navigator === "undefined") return "fr";
  return normalizeLanguage(navigator.language || navigator.languages?.[0]);
}

export function getStoredLanguage() {
  try {
    return normalizeLanguage(localStorage.getItem(STORAGE_KEY) || detectBrowserLanguage());
  } catch {
    return "fr";
  }
}

export function hasStoredLanguageChoice() {
  try {
    return localStorage.getItem(CHOSEN_KEY) === "1";
  } catch {
    return false;
  }
}

export function setStoredLanguage(language, markChosen = true) {
  const next = normalizeLanguage(language);
  try {
    localStorage.setItem(STORAGE_KEY, next);
    if (markChosen) localStorage.setItem(CHOSEN_KEY, "1");
  } catch {}
  if (typeof document !== "undefined") {
    document.documentElement.lang = next;
  }
  return next;
}

function readPath(source, key) {
  return key.split(".").reduce((value, part) => value?.[part], source);
}

export function translate(language, key, values = {}) {
  const lang = normalizeLanguage(language);
  const template = readPath(dictionaries[lang], key) ?? readPath(dictionaries.fr, key) ?? key;
  if (typeof template !== "string") return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? "");
}

export function getOutputLanguageLabel(language) {
  return normalizeLanguage(language) === "en" ? "English" : "French";
}

