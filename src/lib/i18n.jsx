const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => getStoredLanguage());
  const [hasChosenLanguage, setHasChosenLanguage] = useState(() => hasStoredLanguageChoice());

  useEffect(() => {
    setStoredLanguage(language, false);
  }, [language]);

  const value = useMemo(() => {
    const setLanguage = (nextLanguage, markChosen = true) => {
      const next = setStoredLanguage(nextLanguage, markChosen);
      setLanguageState(next);
      if (markChosen) setHasChosenLanguage(true);
    };

    return {
      language,
      isEnglish: language === "en",
      hasChosenLanguage,
      setLanguage,
      chooseLanguage: (nextLanguage) => setLanguage(nextLanguage, true),
      t: (key, values) => translate(language, key, values),
    };
  }, [language, hasChosenLanguage]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useTranslation() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useTranslation must be used within LanguageProvider");
  return context;
}
